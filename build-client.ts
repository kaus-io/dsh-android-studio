/**
 * Build the merged Android Studio browser artifact.
 *
 * Sources: the Android workbench client (`client.view.ts` + `ui-model.ts` +
 * `locale/*.json`) and the IDE-grade code reader under `src/reader`.
 * `client.js` is the generated artifact loaded by the DSH module table; React
 * stays external and comes from the host module table.
 */
import assert from 'node:assert/strict'
import fs from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { build } from 'esbuild'

const root = path.dirname(fileURLToPath(import.meta.url))
const pkg = JSON.parse(await fs.readFile(path.join(root, 'package.json'), 'utf8')) as { name: string; version: string }
const target = path.join(root, 'client.js')
const temp = path.join(root, '.client.build.js')

try {
  await build({
    entryPoints: [path.join(root, 'src/client.tsx')],
    outfile: temp,
    bundle: true,
    format: 'cjs',
    platform: 'browser',
    target: 'es2022',
    jsx: 'automatic',
    external: ['react', 'react/jsx-runtime'],
    legalComments: 'none',
    logLevel: 'silent',
    banner: {
      js:
        `// Android Studio ${pkg.version}. Generated by build-client.mjs; edit client.view.ts, ui-model.ts and src/.\n` +
        `window.__ModuleLoader__.load({ id: ${JSON.stringify(pkg.name)}, factory: (require) => { const module = { exports: {} }; const exports = module.exports;`,
    },
    footer: { js: 'return module.exports; } });' },
  })
  const generated = await fs.readFile(temp, 'utf8')
  if (process.argv.includes('--check')) {
    const current = await fs.readFile(target, 'utf8')
    assert.equal(current, generated, 'client.js is stale; run node build-client.mjs')
    console.log(`Client artifact is current: Android Studio ${pkg.version} (${Buffer.byteLength(generated)} bytes)`)
  } else {
    await fs.writeFile(target, generated, 'utf8')
    console.log(`Built Android Studio ${pkg.version}: ${Buffer.byteLength(generated)} bytes`)
  }
} finally {
  await fs.rm(temp, { force: true })
}
